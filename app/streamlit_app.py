import streamlit as st
from src.config import Settings
from src.integrations.datadog_client import DatadogClient
from src.agents.triage_agent import TriageAgent
from src.agents.trace_agent import TraceAgent
from src.agents.fix_agent import FixAgent
from src.integrations.elevenlabs_tts import ElevenLabsTTS
from src.integrations.braintrust_client import BraintrustClient

st.set_page_config(page_title="VoiceOps", layout="wide")
st.title("VoiceOps: Self-Improving Voice Incident Agent")

# -----------------------------
# Config status
# -----------------------------
st.subheader("Config status")
braintrust = BraintrustClient()
braintrust_status = braintrust.status()
st.write({
    "DD_API_KEY_set": bool(Settings.DD_API_KEY),
    "DD_APP_KEY_set": bool(Settings.DD_APP_KEY),
    "BRAINTRUST_API_KEY_set": bool(Settings.BRAINTRUST_API_KEY),
    "BRAINTRUST_PROJECT_set": bool(Settings.BRAINTRUST_PROJECT),
    "BRAINTRUST_enabled": bool(braintrust_status.get("enabled")),
    "BRAINTRUST_reason": braintrust_status.get("reason"),
    "ELEVENLABS_API_KEY_set": bool(Settings.ELEVENLABS_API_KEY),
    "ELEVENLABS_VOICE_ID_set": bool(Settings.ELEVENLABS_VOICE_ID),
})

st.divider()

# -----------------------------
# Inputs
# -----------------------------
st.subheader("Real-Time Log Monitoring")

service = st.text_input("Service name", value="api")
minutes = st.slider("Lookback window (minutes)", 1, 30, 5)

# -----------------------------
# Single button: Fetch -> Triage -> Trace -> Fix -> Voice
# -----------------------------
if st.button("Fetch Incident", key="fetch_incident"):
    dd = DatadogClient()
    incident = dd.fetch_incident(service, minutes)

    triage = TriageAgent()
    incident = triage.enrich_incident(incident)

    trace = TraceAgent()
    incident = trace.enrich_incident(incident)

    fix = FixAgent()
    incident = fix.enrich_incident(incident)

    st.success("Incident detected + triaged + traced + fix-proposed")
    st.json(incident.model_dump())
    if incident.trace_candidates:
        st.caption("Top trace candidates")
        st.table([candidate.model_dump() for candidate in incident.trace_candidates])
    if incident.fix_proposals:
        st.caption("Top fix proposals")
        st.table([proposal.model_dump() for proposal in incident.fix_proposals])

    # Voice summary text
    top_trace = incident.trace_candidates[0].file_path if incident.trace_candidates else "unknown location"
    top_fix = incident.fix_proposals[0].title if incident.fix_proposals else "no concrete fix yet"
    voice_text = (
        f"{incident.summary}. "
        f"Likely source file is {top_trace}. "
        f"Top fix proposal: {top_fix}. "
        f"Service is {incident.service}. Severity {incident.severity}. "
        f"Would you like me to generate an optimization patch?"
    )

    # Generate + play voice
    voice_generated = False
    try:
        tts = ElevenLabsTTS()
        audio_path = tts.synthesize_to_file(voice_text)

        with open(audio_path, "rb") as f:
            st.audio(f.read(), format="audio/mpeg")

        st.caption("Voice summary generated by ElevenLabs")
        voice_generated = True
    except Exception as e:
        st.error(f"Voice generation failed: {e}")

    braintrust_logged = braintrust.log_incident_run(
        incident,
        service=service,
        minutes=minutes,
        source=dd.last_source,
        voice_generated=voice_generated,
    )
    if braintrust_logged:
        st.caption("Run logged to Braintrust")
